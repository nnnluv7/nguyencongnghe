// Read HTML shells from the deployed static assets (dist/) through the
// Pages ASSETS binding — the Workers replacement for node:fs reads of public/.
//
// IMPORTANT: env.ASSETS.fetch() applies the _redirects rules, and every
// public shell path is covered by a rewrite to a Function, so fetching the
// shells at their public paths 404s. The build (scripts/build-public.mjs,
// CF_PAGES=1) therefore copies every optimized HTML shell to /_ncn-shells/,
// a prefix no redirect rule matches, and this reader fetches from there.
//
// Used for: home/index shells, original article HTML, site-page shells.
// Files that are NOT in public/ (private event/gvgs templates, library admin
// HTML, article shell) are embedded at build time instead; see
// private-assets.mjs (generated by scripts/build-public.mjs when CF_PAGES=1).

export function createAssetReader(env, request) {
  const assets = env?.ASSETS;
  if (!assets) throw new Error('Missing ASSETS binding');
  const base = new URL(request.url).origin;
  // `publicPath` is a path under public/, e.g. 'index.html' or
  // '2020/10/shrink-volume-32-phan-mem-chia-o-cung.html'.
  async function readShell(publicPath) {
    const clean = '/_ncn-shells/' + String(publicPath).replace(/^\/+/, '');
    const res = await assets.fetch(new Request(base + clean));
    if (!res.ok) throw new Error('Missing shell ' + clean + ' (' + res.status + ')');
    return res.text();
  }
  return {readShell};
}
